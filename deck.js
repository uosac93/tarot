/* 슈트 × 주제 — 문장의 앞머리 */
const SUIT_TOPIC = {
 wand:  {love:'끌림과 추진력으로', money:'벌이와 도전으로', work:'열정과 실행으로', self:'의욕과 행동으로'},
 cup:   {love:'마음과 정으로',     money:'사람과 인연으로', work:'관계와 분위기로', self:'감정과 치유로'},
 sword: {love:'말과 판단으로',     money:'계산과 결단으로', work:'전략과 논리로',   self:'생각과 각성으로'},
 penta: {love:'현실과 안정으로',   money:'돈과 자산으로',   work:'성과와 보상으로', self:'몸과 기반으로'}
};

function buildDeck(){
  const d = MAJOR.map(m => ({
    id:'M'+m.n, type:'major', num:m.n, name:m.k, en:m.e, glyph:m.g, img:'cards/M'+m.n+'.jpg',
    up:m.up, rv:m.rv, txt:{love:m.love, money:m.money, work:m.work, self:m.self},
    color:'#7b5ea7'
  }));
  for (const [sk, s] of Object.entries(SUITS)) {
    RANKS.forEach((rk, i) => {
      const nm = s.k + ' ' + rk.k;
      const t = {};
      for (const tp of ['love','money','work','self']) {
        t[tp] = [ SUIT_TOPIC[sk][tp] + ' ' + rk.up + ' — ' + s.f,
                  SUIT_TOPIC[sk][tp] + ' ' + rk.rv + ' — ' + s.f ];
      }
      const IMG = {wand:'Wands', cup:'Cups', sword:'Swords', penta:'Pents'};
      d.push({ id:sk+rk.r, type:'minor', suit:sk, rank:rk.r, num:i+1,
        name:nm, en:s.e+' '+rk.r, glyph:s.g, img:'cards/'+IMG[sk]+(i+1)+'.jpg',
        up:[...rk.ku, s.f.split('·')[0]], rv:[...rk.kr, s.f.split('·')[0]],
        txt:t, color:s.color });
    });
  }
  return d;
}
const DECK = buildDeck();
